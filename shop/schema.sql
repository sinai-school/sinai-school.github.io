CREATE TABLE IF NOT EXISTS msgs (id INTEGER PRIMARY KEY, kind TEXT, url TEXT, txt TEXT, dt TEXT, at INTEGER);
CREATE TABLE IF NOT EXISTS products (id TEXT PRIMARY KEY, src TEXT, post INTEGER, auto TEXT, ov TEXT DEFAULT '{}', ai TEXT, media TEXT DEFAULT '[]', dt TEXT, at INTEGER);
CREATE TABLE IF NOT EXISTS imgs (k TEXT PRIMARY KEY, ct TEXT, data BLOB, at INTEGER);
CREATE TABLE IF NOT EXISTS imgq (k TEXT PRIMARY KEY, url TEXT, tries INTEGER DEFAULT 0, at INTEGER);
CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, v TEXT);
CREATE TABLE IF NOT EXISTS sess (tok TEXT PRIMARY KEY, exp INTEGER);
CREATE TABLE IF NOT EXISTS log (at INTEGER, msg TEXT);
CREATE INDEX IF NOT EXISTS products_post ON products(post);
CREATE TABLE IF NOT EXISTS st_day (d TEXT, k TEXT, n INTEGER DEFAULT 0, PRIMARY KEY(d,k));
CREATE TABLE IF NOT EXISTS st_vis (d TEXT, v TEXT, PRIMARY KEY(d,v));
CREATE TABLE IF NOT EXISTS st_prod (d TEXT, p TEXT, v INTEGER DEFAULT 0, o INTEGER DEFAULT 0, PRIMARY KEY(d,p));
CREATE TABLE IF NOT EXISTS st_q (d TEXT, q TEXT, n INTEGER DEFAULT 0, z INTEGER DEFAULT 0, PRIMARY KEY(d,q));
